const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = require('../server/data-path.cjs');
fs.mkdirSync(root, { recursive: true });
const archive = path.join(root, 'jmdict-eng-3.6.2+20261026175559.json.tgz');
const sha = '809d104fe3c1e0ab328ff265bdc52b5eed1f9b669088fd199ef4e713812958a3';
require('./pinned-download.cjs')(archive, sha, ['https://github.com/scriptin/jmdict-simplified/releases/download/3.6.2%2B20261026175559/jmdict-eng-3.6.2%2B20261026175559.json.tgz']);
const output = execFileSync('tar', ['-xOzf', archive, 'jmdict-eng-3.6.2.json'], { maxBuffer: 200 * 1024 * 1024 });
const target = path.join(root, 'jmdict.json');
fs.writeFileSync(target + '.building', output);
fs.renameSync(target + '.building', target);
console.log('Pinned JMdict English dataset installed. EDRDG CC BY-SA 4.0; see THIRD_PARTY.md.');
require('./setup-names.cjs');
require('./setup-pitch.cjs');
